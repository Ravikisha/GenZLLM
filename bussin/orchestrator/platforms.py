class ColabAdapter(Adapter):
    """Drives the official Colab CLI.

    `colab run` executes a script on a fresh VM and releases it afterwards,
    which is exactly the shape the orchestrator wants. Two caveats:

    * The CLI is Linux/macOS only, so this works on a CI runner but not from a
      Windows workstation.
    * Whether `colab run` is available on the *free* tier is not documented.
      `preflight` reports what it finds rather than assuming.
    """

    name = "colab"
    automatable = True

    def preflight(self) -> tuple[bool, str]:
        exe = shutil.which("colab")
        if not exe:
            return False, "colab CLI not installed (`pip install google-colab-cli`)"
        try:
            p = subprocess.run(["colab", "sessions"], capture_output=True,
                               text=True, timeout=60)
        except Exception as exc:
            return False, f"colab CLI failed: {type(exc).__name__}"
        if p.returncode != 0:
            return False, f"colab CLI not authenticated: {p.stderr.strip()[:160]}"
        return True, "ok"

    def dispatch(self, config_path: str, worker_id: str) -> DispatchResult:
        ok, why = self.preflight()
        if not ok:
            return DispatchResult(False, self.name, detail=why, retryable=False)
        script = Path(tempfile.mkdtemp(prefix="bussin_colab_")) / "worker.py"
        script.write_text(
            KAGGLE_NOTEBOOK.format(
                hf_token=self.cfg.creds.hf_token or "",
                repo_url=self.repo_url if hasattr(self, "repo_url") else
                os.environ.get("BUSSIN_REPO_URL", ""),
                config=config_path,
            ).replace("/kaggle/working", "/content"),
            encoding="utf-8",
        )
        try:
            p = subprocess.Popen(
                ["colab", "run", "--gpu", "T4", "-f", str(script)],
                stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
            )
            return DispatchResult(True, self.name, ref=str(p.pid),
                                  detail="colab run launched")
        except Exception as exc:
            return DispatchResult(False, self.name,
                                  detail=f"{type(exc).__name__}: {str(exc)[:200]}")


class LightningAdapter(Adapter):
    name = "lightning"
    automatable = True

    def preflight(self) -> tuple[bool, str]:
        if not os.environ.get("LIGHTNING_API_KEY"):
            return False, "LIGHTNING_API_KEY not set"
        if not shutil.which("lightning"):
            return False, "lightning CLI not installed"
        return True, "ok"

    def dispatch(self, config_path: str, worker_id: str) -> DispatchResult:
        return DispatchResult(False, self.name, detail="adapter not implemented",
                              retryable=False)


class ManualAdapter(Adapter):
    """Platforms with no API. The orchestrator surfaces them, never drives them."""

    automatable = False

    def __init__(self, cfg: ProjectConfig, name: str) -> None:
        super().__init__(cfg)
        self.name = name

    def preflight(self) -> tuple[bool, str]:
        return False, f"{self.name} has no API; run it by hand"


def build_adapters(cfg: ProjectConfig, code_slug: str = "",
                   datasets: list[str] | None = None) -> dict[str, Adapter]:
    return {
        "kaggle-tpu": KaggleAdapter(cfg, "tpu", code_slug, datasets),
        "kaggle-gpu": KaggleAdapter(cfg, "gpu", code_slug, datasets),
        "colab": ColabAdapter(cfg),
        "lightning": LightningAdapter(cfg),
        "studiolab": ManualAdapter(cfg, "studiolab"),
    }
