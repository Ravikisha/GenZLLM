KAGGLE_NOTEBOOK = '''\
# Bussin worker -- generated by the orchestrator. Do not edit in the UI.
#
# The source arrives as a mounted Kaggle Dataset rather than a git clone:
# attached inputs are mounted, not downloaded, so they cost no session time.
import os, subprocess, sys, time
T0 = time.time()
os.environ["HF_HUB_ENABLE_HF_TRANSFER"] = "1"
os.environ["TOKENIZERS_PARALLELISM"] = "false"

# Prefer Kaggle Secrets so the token never sits in kernel source. Add it under
# Add-ons -> Secrets as HF_TOKEN. The embedded value is a fallback for the
# private kernel the orchestrator pushes.
try:
    from kaggle_secrets import UserSecretsClient
    os.environ["HF_TOKEN"] = UserSecretsClient().get_secret("HF_TOKEN")
    print("HF token from Kaggle secrets", flush=True)
except Exception:
    os.environ["HF_TOKEN"] = "{hf_token}"
    print("HF token from kernel source (add a Kaggle secret to avoid this)", flush=True)

# Find the mounted source rather than assuming a path. Kaggle derives the
# mount folder from the dataset slug, but not always the way you expect, and a
# wrong guess wastes a whole dispatch.
INPUT = "/kaggle/input"
print("mounted inputs:", os.listdir(INPUT) if os.path.isdir(INPUT) else "<none>",
      flush=True)

CODE = None
for base, dirs, files in os.walk(INPUT):
    if os.path.basename(base) == "relay" and "bootstrap.py" in files:
        CODE = os.path.dirname(os.path.dirname(base))   # .../<root>/bussin/relay
        break
    if base.count(os.sep) > INPUT.count(os.sep) + 4:
        dirs[:] = []                                     # keep the walk shallow
if CODE is None:
    raise SystemExit(
        f"bussin source not found under {{INPUT}}; attach {code_slug}. "
        f"Present: {{os.listdir(INPUT) if os.path.isdir(INPUT) else []}}"
    )
print("source:", CODE, flush=True)
sys.path.insert(0, CODE)
os.chdir(CODE)

subprocess.run([sys.executable, "-m", "pip", "install", "-q",
                "hf_transfer", "safetensors", "huggingface_hub", "pyyaml", "regex"],
               check=False)
print(f"setup {{time.time() - T0:.1f}}s", flush=True)

CONFIG = "{config}"
if not os.path.isabs(CONFIG):
    CONFIG = os.path.join(CODE, CONFIG)
if not os.path.exists(CONFIG):
    raise SystemExit(f"config not found: {{CONFIG}}")

from bussin.relay.bootstrap import run
sys.exit(run(CONFIG, local_root=None))
'''

KAGGLE_METADATA = {
    "id": "",
    "title": "",
    "code_file": "worker.py",
    "language": "python",
    "kernel_type": "script",
    "is_private": True,
    "enable_gpu": False,
    "enable_tpu": False,
    "enable_internet": True,
    "dataset_sources": [],
    "competition_sources": [],
    "kernel_sources": [],
    "model_sources": [],
}


class KaggleAdapter(Adapter):
    name = "kaggle"
    automatable = True

    def __init__(self, cfg: ProjectConfig, accelerator: str = "gpu",
                 code_slug: str = "", datasets: list[str] | None = None) -> None:
        super().__init__(cfg)
        self.accelerator = accelerator          # gpu | tpu
        self.name = f"kaggle-{accelerator}"
        self.code_slug = code_slug or os.environ.get(
            "BUSSIN_CODE_DATASET",
            f"{cfg.creds.kaggle_username}/bussin-code" if cfg.creds.kaggle_username else "",
        )
        self.datasets = datasets or []
        self._api = None

    @property
    def code_dir(self) -> str:
        return f"/kaggle/input/{self.code_slug.split('/')[-1]}"

    # -------------------------------------------------------------- #

    def api(self):
        if self._api is None:
            self.cfg.creds.export_kaggle()
            self.cfg.creds.write_kaggle_json()
            from kaggle.api.kaggle_api_extended import KaggleApi

            api = KaggleApi()
            api.authenticate()
            self._api = api
        return self._api

    def preflight(self) -> tuple[bool, str]:
        if not (self.cfg.creds.kaggle_username and self.cfg.creds.kaggle_key):
            return False, "KAGGLE_USERNAME / KAGGLE_KEY not set"
        try:
            self.api().kernels_list(mine=True, page_size=1)
        except Exception as exc:
            msg = str(exc)
            if "401" in msg or "Unauthorized" in msg:
                # KGAT_ access tokens expire after ~3 hours. Unattended running
                # needs a legacy API key (kaggle.com/settings/api -> Legacy API
                # Credentials), which does not expire.
                return False, (
                    "Kaggle credentials rejected (401). A KGAT_ access token "
                    "expires after ~3h; use a Legacy API key for unattended runs."
                )
            return False, f"{type(exc).__name__}: {msg[:160]}"
        if not self.code_slug:
            return False, "no code dataset (run scripts/push_code_dataset.py)"
        try:
            self.api().dataset_status(self.code_slug)
        except Exception:
            return False, (f"code dataset {self.code_slug} not found -- "
                           f"run scripts/push_code_dataset.py")
        return True, "ok"

    def _slug(self, worker_id: str) -> str:
        return f"{self.cfg.creds.kaggle_username}/bussin-{self.accelerator}-worker"

    def dispatch(self, config_path: str, worker_id: str) -> DispatchResult:
        ok, why = self.preflight()
        if not ok:
            return DispatchResult(False, self.name, detail=why, retryable=False)

        slug = self._slug(worker_id)
        work = Path(tempfile.mkdtemp(prefix="bussin_kernel_"))
        try:
            (work / "worker.py").write_text(
                KAGGLE_NOTEBOOK.format(
                    hf_token=self.cfg.creds.hf_token or "",
                    code_dir=self.code_dir,
                    code_slug=self.code_slug,
                    config=config_path,
                ),
                encoding="utf-8",
            )
            meta = dict(KAGGLE_METADATA)
            meta.update(
                id=slug,
                title=f"bussin {self.accelerator} worker",
                enable_gpu=self.accelerator == "gpu",
                enable_tpu=self.accelerator == "tpu",
                dataset_sources=[self.code_slug] + list(self.datasets),
            )
            (work / "kernel-metadata.json").write_text(
                json.dumps(meta, indent=2), encoding="utf-8"
            )
            self.api().kernels_push(str(work))
            return DispatchResult(True, self.name, ref=slug,
                                  detail=f"pushed {slug}")
        except Exception as exc:
            return DispatchResult(False, self.name,
                                  detail=f"{type(exc).__name__}: {str(exc)[:200]}")
        finally:
            shutil.rmtree(work, ignore_errors=True)

    def status(self, ref: str) -> str:
        try:
            s = self.api().kernels_status(ref)
            raw = (getattr(s, "status", None) or
                   (s.get("status") if isinstance(s, dict) else "") or "")
            raw = str(raw).lower()
        except Exception:
            return "unknown"
        if "running" in raw or "queued" in raw:
            return "running"
        if "complete" in raw:
            return "complete"
        if "error" in raw or "cancel" in raw:
            return "error"
        return "unknown"


