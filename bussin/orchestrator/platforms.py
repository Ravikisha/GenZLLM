"""Platform adapters.

Each adapter answers two questions: can I dispatch a training session right
now, and did the last one finish? Everything else -- who holds the run, where
the checkpoint is, what step we are on -- is the relay's job, not the adapter's.

That split is what keeps the orchestrator crash-safe. An adapter never has to
track a job to completion, because the lease already does: if a dispatched
session dies, its lease expires and the next tick redispatches.

Automation status per platform:

  kaggle-gpu / kaggle-tpu   official API (`kernels push`), fully automatable
  colab                     official CLI (`colab run`), headless; free-tier
                            support is UNVERIFIED -- test before relying on it
  lightning                 SDK; adapter is a stub
  studiolab                 no API at all; manual only
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import tempfile
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from ..config import ProjectConfig


@dataclass
class DispatchResult:
    ok: bool
    platform: str
    ref: str = ""
    detail: str = ""
    retryable: bool = True


class Adapter:
    name = "base"
    automatable = False

    def __init__(self, cfg: ProjectConfig) -> None:
        self.cfg = cfg

    def preflight(self) -> tuple[bool, str]:
        """Can this adapter dispatch right now?"""
        return False, "not implemented"

    def dispatch(self, config_path: str, worker_id: str) -> DispatchResult:
        raise NotImplementedError

    def status(self, ref: str) -> str:
        """running | complete | error | unknown"""
        return "unknown"


